"""Figures for the paper.

Current figures generated by this module:
  - prefix_overlap.pdf     : within-vs-cross prefix-share bar chart (Discogs-VI)
                             from runs/*_semid_report.json
  - prefix_overlap_x.pdf   : cross-dataset (Covers80) variant
  - tsne.pdf               : (optional) t-SNE of codebook-expanded SemIDs
                             colored by clique

All paths default to paper/figures/<name>.pdf so LaTeX picks them up
via \\includegraphics{figures/<name>}.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


CONDITIONS = ["random", "encodec", "mert"]
COND_LABELS = {"random": "Random", "encodec": "EnCodec direct", "mert": "MERT-RQ-VAE"}
COND_COLORS = {"random": "#bdbdbd", "encodec": "#8ab4f8", "mert": "#1a73e8"}


def load_reports(dataset: str, runs_dir: Path) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for cond in CONDITIONS:
        p = runs_dir / f"{dataset}_{cond}_semid_report.json"
        if not p.exists():
            print(f"warn: {p} missing")
            continue
        with p.open() as f:
            out[cond] = json.load(f)
    return out


def make_prefix_overlap_fig(
    reports: dict[str, dict], out_path: Path, title: str,
) -> None:
    """Grouped bar chart: within vs cross prefix-share at c1, c1+c2 per condition."""
    conds = [c for c in CONDITIONS if c in reports]
    metrics = ["p1", "p12"]
    metric_labels = ["$p_1$ (share $c_1$)", "$p_{12}$ (share $c_1, c_2$)"]

    fig, axes = plt.subplots(1, 2, figsize=(6.5, 2.6), sharey=False)
    x = np.arange(len(conds))
    width = 0.36

    for ax, m, ml in zip(axes, metrics, metric_labels):
        within = [reports[c]["prefix_overlap"]["within"][m] for c in conds]
        cross = [reports[c]["prefix_overlap"]["cross"][m] for c in conds]
        ax.bar(x - width / 2, within, width, label="within clique",
               color=[COND_COLORS[c] for c in conds],
               edgecolor="black", linewidth=0.6)
        ax.bar(x + width / 2, cross, width, label="cross clique",
               color=[COND_COLORS[c] for c in conds],
               edgecolor="black", linewidth=0.6, hatch="///")
        ax.set_xticks(x)
        ax.set_xticklabels([COND_LABELS[c] for c in conds], rotation=15, ha="right", fontsize=8)
        ax.set_ylabel(ml, fontsize=9)
        ax.tick_params(axis="y", labelsize=8)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.grid(axis="y", alpha=0.3, linewidth=0.5)
        # Annotate within/cross ratio on top of within bar
        for i, c in enumerate(conds):
            w = within[i]; cr = cross[i]
            ratio = (w / cr) if cr > 0 else float("nan")
            label = f"{ratio:.1f}$\\times$" if not np.isnan(ratio) else "—"
            ax.text(i - width / 2, w, label,
                    ha="center", va="bottom", fontsize=7, fontweight="bold")

    # One legend for both panels, in a clean spot
    handles = [
        plt.Rectangle((0, 0), 1, 1, facecolor="white", edgecolor="black", linewidth=0.6),
        plt.Rectangle((0, 0), 1, 1, facecolor="white", edgecolor="black", linewidth=0.6, hatch="///"),
    ]
    fig.legend(handles, ["within clique", "cross clique"],
               loc="upper center", ncol=2, frameon=False, fontsize=8,
               bbox_to_anchor=(0.5, 1.02))
    fig.suptitle(title, fontsize=10, y=1.08)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, bbox_inches="tight", dpi=300)
    plt.close(fig)
    print(f"Wrote {out_path}")


def make_tsne_fig(
    semids_csv: Path, cliques_csv: Path, codebooks_pkl: Path,
    out_path: Path, n_cliques: int = 20, seed: int = 42,
) -> None:
    """t-SNE of codebook-expanded SemIDs, colored by the top-N most-populous cliques."""
    import pickle

    from sklearn.manifold import TSNE

    semids: dict[str, tuple[int, int, int]] = {}
    with semids_csv.open() as f:
        for r in csv.DictReader(f):
            semids[r["track_id"]] = (int(r["c1"]), int(r["c2"]), int(r["c3"]))

    cliques: dict[str, str] = {}
    with cliques_csv.open() as f:
        for r in csv.DictReader(f):
            cliques[r["track_id"]] = r["clique_id"]

    with codebooks_pkl.open("rb") as f:
        codebooks = pickle.load(f)
    # Expand each SemID to a vector: concat the three level centroids
    track_ids: list[str] = []
    vecs: list[np.ndarray] = []
    clique_ids: list[str] = []
    for tid, (c1, c2, c3) in semids.items():
        if tid not in cliques:
            continue
        v = np.concatenate([codebooks[0].cluster_centers_[c1],
                            codebooks[1].cluster_centers_[c2],
                            codebooks[2].cluster_centers_[c3]])
        vecs.append(v)
        track_ids.append(tid)
        clique_ids.append(cliques[tid])

    X = np.stack(vecs, axis=0)
    print(f"t-SNE input: {X.shape}")

    # Restrict to top-N most-populous cliques for legibility
    from collections import Counter
    counts = Counter(clique_ids)
    top_cliques = [c for c, _ in counts.most_common(n_cliques)]
    mask = np.array([c in top_cliques for c in clique_ids])
    X_top = X[mask]
    clique_top = [clique_ids[i] for i in range(len(clique_ids)) if mask[i]]
    print(f"Plotting {X_top.shape[0]} tracks from top-{n_cliques} cliques")

    emb = TSNE(n_components=2, perplexity=min(30, X_top.shape[0] // 4),
               random_state=seed, init="pca").fit_transform(X_top)

    fig, ax = plt.subplots(figsize=(5.0, 4.0))
    cmap = plt.colormaps.get_cmap("tab20")
    for i, cid in enumerate(top_cliques):
        idxs = [j for j, c in enumerate(clique_top) if c == cid]
        ax.scatter(emb[idxs, 0], emb[idxs, 1],
                   s=24, alpha=0.85, color=cmap(i % 20), edgecolors="black",
                   linewidth=0.3, label=cid if i < 10 else None)
    ax.set_xticks([]); ax.set_yticks([])
    ax.set_xlabel("t-SNE dim 1", fontsize=9)
    ax.set_ylabel("t-SNE dim 2", fontsize=9)
    for spine in ax.spines.values():
        spine.set_linewidth(0.5)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, bbox_inches="tight", dpi=300)
    plt.close(fig)
    print(f"Wrote {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs-dir", default="runs")
    parser.add_argument("--out-dir", default="paper/figures")
    parser.add_argument("--skip-tsne", action="store_true")
    args = parser.parse_args()

    runs_dir = Path(args.runs_dir)
    out_dir = Path(args.out_dir)

    # 1. Prefix-overlap bar chart for Discogs-VI
    reports = load_reports("discogs_vi", runs_dir)
    if reports:
        make_prefix_overlap_fig(
            reports,
            out_dir / "prefix_overlap.pdf",
            title="Discogs-VI: within- vs cross-clique prefix-share",
        )

    # 2. Same for Covers80 (cross-dataset; smaller signal but worth showing)
    reports_c80 = load_reports("covers80", runs_dir)
    if reports_c80:
        make_prefix_overlap_fig(
            reports_c80,
            out_dir / "prefix_overlap_covers80.pdf",
            title="Covers80 (cross-dataset): within- vs cross-clique prefix-share",
        )

    # 3. t-SNE of MERT-RQ-VAE SemIDs (codebook-expanded)
    if not args.skip_tsne:
        try:
            make_tsne_fig(
                semids_csv=Path("data/semantic_ids/discogs_vi_mert.csv"),
                cliques_csv=Path("data/splits/discogs_vi_audio.csv"),
                codebooks_pkl=Path("data/semantic_ids/mert_codebooks.pkl"),
                out_path=out_dir / "tsne.pdf",
                n_cliques=20,
            )
        except Exception as e:
            print(f"t-SNE skipped: {e!r}")


if __name__ == "__main__":
    main()
